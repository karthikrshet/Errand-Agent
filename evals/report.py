"""Run every eval scenario offline and generate evals/RESULTS.md and evals/results.csv.

The table is produced by this run (never hand-written): each row's 'actual' column is computed
from the trace, the agent DB and the provider ledger, and every row also carries the result of
the global invariant checker.
"""

from __future__ import annotations

import csv
import subprocess
import sys
import time
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from errand.llm.cassette import CassetteClient
from evals.harness import EvalRun, EvalScenario, execute
from evals.invariants import check_all
from evals.scenarios import all_scenarios

ROOT = Path(__file__).resolve().parent
RUNS = ROOT / ".runs"
CASSETTES = ROOT / "cassettes"


@dataclass
class Row:
    sid: str
    name: str
    expected: str
    actual: str
    passed: bool
    notes: str
    failures: list[str]


def summarize(run: EvalRun) -> str:
    st = run.world.agent.load("eval")
    parts = [f"final={st.status.value}", f"new_bookings={run.new_bookings()}"]
    tools = [str(x.get("tool")) for x in run.tool_calls()]
    for t in ("book", "cancel", "reschedule", "get_booking_status"):
        if tools.count(t):
            parts.append(f"{t}x{tools.count(t)}")
    grants = len(run.tracer.of_kind("approval.granted"))
    parts.append(f"grants={grants}")
    flagged = len(run.tracer.of_kind("security.injection_detected"))
    if flagged:
        parts.append(f"injections_flagged={flagged}")
    if run.tracer.of_kind("limit.hit"):
        parts.append("limit_hit")
    if run.tracer.of_kind("llm.fallback"):
        parts.append("llm_fallback")
    if run.crashes:
        parts.append(f"crash={'+'.join(run.crashes)}")
    return "; ".join(parts)


def run_one(sc: EvalScenario, llm: Any = None, suffix: str = "") -> Row:
    run = execute(sc, RUNS / (sc.sid + suffix), llm)
    own = sc.check(run)
    invariants = check_all(run)
    inv_fail = [f"{k}: {m}" for k, msgs in invariants.items() for m in msgs]
    failures = own + inv_fail
    totals = run.tracer.totals
    inv = (
        "I1-I6 ok"
        if not inv_fail
        else "INVARIANT FAIL " + ",".join(k for k, v in invariants.items() if v)
    )
    notes = (
        f"{inv}; tool_calls={totals.tool_calls}; model_calls={totals.model_calls}; "
        f"tokens={totals.input_tokens}/{totals.output_tokens}; seed={sc.seed}"
    )
    name = sc.name + (" [recorded real-LLM cassette]" if suffix else "")
    return Row(sc.sid + suffix, name, sc.expected, summarize(run), not failures, notes, failures)


def cassette_rows(scenarios: list[EvalScenario]) -> list[Row]:
    """Replay every recorded cassette offline (real model output, no network)."""
    rows = []
    by_id = {s.sid: s for s in scenarios}
    for path in sorted(CASSETTES.glob("*.jsonl")):
        sc = by_id.get(path.stem)
        if sc is not None:
            rows.append(run_one(sc, CassetteClient(path), suffix="-rec"))
    return rows


def _git_sha() -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            capture_output=True, text=True, check=True, cwd=ROOT,
        )  # fmt: skip
        dirty = subprocess.run(
            ["git", "status", "--porcelain"], capture_output=True, text=True, cwd=ROOT, check=False
        ).stdout.strip()
        return out.stdout.strip() + ("-dirty" if dirty else "")
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def _md_cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def write(rows: list[Row], elapsed: float) -> None:
    passed = sum(r.passed for r in rows)
    header = (
        f"# Eval results\n\nGenerated by `make eval` (evals/report.py) at "
        f"{datetime.now(UTC):%Y-%m-%d %H:%M:%SZ} on commit `{_git_sha()}`. "
        f"**{passed}/{len(rows)} passed** in {elapsed:.1f}s, fully offline (scripted model).\n\n"
        "Every row is also checked against the global invariants I1-I6 "
        "(see evals/invariants.py).\n\n"
        "| # | scenario | expected | actual | pass/fail | notes |\n"
        "|---|---|---|---|---|---|\n"
    )
    lines = [
        f"| {r.sid} | {r.name} | {_md_cell(r.expected)} | {_md_cell(r.actual)} | "
        f"{'PASS' if r.passed else 'FAIL'} | {_md_cell(r.notes)} |"
        for r in rows
    ]
    failures = [
        f"\n### {r.sid} {r.name}\n" + "\n".join(f"- {f}" for f in r.failures)
        for r in rows
        if not r.passed
    ]
    body = header + "\n".join(lines) + "\n"
    if failures:
        body += "\n## Failures\n" + "\n".join(failures) + "\n"
    (ROOT / "RESULTS.md").write_text(body, encoding="utf-8", newline="\n")
    with (ROOT / "results.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["scenario", "expected", "actual", "pass/fail", "notes"])
        for r in rows:
            w.writerow([f"{r.sid} {r.name}", r.expected, r.actual,
                        "PASS" if r.passed else "FAIL", r.notes])  # fmt: skip


def main(argv: list[str]) -> int:
    only = set(argv)
    scenarios = [s for s in all_scenarios() if not only or s.sid in only or s.name in only]
    started = time.perf_counter()
    rows = [run_one(s) for s in scenarios]
    if not only:
        rows += cassette_rows(scenarios)
    elapsed = time.perf_counter() - started
    if not only:
        write(rows, elapsed)
    for r in rows:
        mark = "PASS" if r.passed else "FAIL"
        print(f"{mark} {r.sid:>4} {r.name:<45} {r.actual}")
        for f in r.failures:
            print(f"       - {f}")
    print(f"{sum(r.passed for r in rows)}/{len(rows)} passed in {elapsed:.1f}s")
    return 0 if all(r.passed for r in rows) else 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
